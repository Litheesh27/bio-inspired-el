FIG5_CAPTION = (
    "Figure 5. The three algorithms' routes before (left) and after (right) "
    "scenario {scenario} under SUMO heavy demand, warm start, on OD pair "
    "{source}->{target}. Closed roads are black; the full street network is "
    "grey. Dijkstra and A* are exact and coincide. Physarum's route is "
    "labelled with the provenance of its reported path -- only "
    "`max_flux_walk` is the model's own extraction, and ~70% of Physarum's "
    "reported paths in the sweep came from a fallback that is Dijkstra on a "
    "subgraph (Phase 8e), so an unlabelled green line would be an unfair "
    "claim. ILLUSTRATIVE: regenerated by a seeded re-run (Phase 9b); the "
    "results Parquet stores path_hops but not the paths, so this figure "
    "cannot be produced from the measured data."
)


def _series_key(record) -> str:
    """Which style series a route belongs to.

    Physarum splits by provenance: `max_flux_walk` is the model's own
    extraction and gets the model-only colour, everything else gets the
    with-fallback colour.
    """
    if record.algorithm != "physarum":
        return record.algorithm
    method = record.extraction_after or record.extraction_before
    return "physarum_walk" if method == "max_flux_walk" else "physarum"


def _route_label(record, phase: str) -> str:
    stretch = getattr(record, f"stretch_{phase}")
    hops = getattr(record, f"hops_{phase}")
    method = getattr(record, f"extraction_{phase}")
    key = _series_key(record)
    # The phase is named explicitly: the legend carries the BEFORE
    # numbers while the right panel's title carries the AFTER ones, and an
    # unlabelled "stretch 1.361" invites the reader to attach it to
    # whichever panel they are looking at.
    text = f"{style.label(key)} — {phase} closure: stretch {stretch:.3f}, {hops} hops"
    if record.algorithm == "physarum":
        text += f"\n    path from: {method}"
    return text


def plot_routes_before_after(
    bundle,
    G: nx.MultiDiGraph,
    out_stem: str | Path,
    algorithms: Sequence[str] = ("dijkstra", "astar", "aco", "physarum"),
) -> list[Path]:
    """Render figure 5 from a `traces.RouteBundle` to PNG + SVG.

    `bundle` is duck-typed rather than imported-and-isinstance'd so this
    module can also be driven from the JSON artifact via a simple namespace
    object, which is what the dashboard export will want.
    """
    import matplotlib.pyplot as plt  # noqa: PLC0415
    from matplotlib.transforms import offset_copy  # noqa: PLC0415

    style.apply_style()

    records = [r for r in bundle.routes if r.algorithm in algorithms]
    all_paths = [r.path_before for r in records if r.path_before]
    all_paths += [r.path_after for r in records if r.path_after]
    all_paths.append(bundle.reference_path)
    all_paths.append(bundle.disrupted_reference_path)

    fig, axes = plt.subplots(1, 2, figsize=(11.0, 3.9))
    panels = (
        (axes[0], "before", "before closure", []),
        (axes[1], "after", f"after {bundle.scenario_id} closure", bundle.removed_edges),
    )

    handles: list[Any] = []
    labels: list[str] = []
    n_corridors = 0

    for ax, phase, title, removed in panels:
        draw_basemap(ax, G)
        if removed:
            n_corridors = draw_removed(ax, G, removed)

        # Draw exact baselines first so the bio-inspired detours sit on top
        # of them where they coincide -- the interesting line should be the
        # visible one.
        ordered = sorted(
            records, key=lambda r: style.ALGO_ORDER.index(_series_key(r))
        )
        for slot, record in enumerate(ordered):
            path = getattr(record, f"path_{phase}")
            if not path:
                continue
            # DECLARED DRAWING OFFSET, not a geometry change. Four routes
            # on a 4x4 km map share long corridors, and whichever is drawn
            # last hides the rest -- in an earlier draft ACO's route
            # appeared to stop halfway because Physarum's ran over its
            # tail, which reads as a failed solve. Each series is shifted
            # by a couple of POINTS in display space (never in lon/lat), so
            # the underlying coordinates and the equal-area aspect are
            # untouched and an overlap shows as parallel lines.
            offset = offset_copy(
                ax.transData,
                fig=fig,
                x=(slot - 1.5) * 1.8,
                y=(slot - 1.5) * 1.8,
                units="points",
            )
            # A* is exact, so it traces Dijkstra's path exactly and would
            # otherwise paint over it and vanish from the figure. Drawn
            # dashed on top, so the coincidence is VISIBLE rather than
            # merely asserted in the caption.
            line = draw_route(
                ax,
                G,
                path,
                color=style.color(_series_key(record)),
                linewidth=2.2 if record.algorithm in style.BIO_ALGOS else 1.8,
                zorder=4 + style.ALGO_ORDER.index(_series_key(record)),
                linestyle=(0, (4, 3)) if record.algorithm == "astar" else "-",
                halo=record.algorithm != "astar",
                transform=offset,
            )
            if phase == "before" and line is not None:
                handles.append(line)
                labels.append(_route_label(record, phase))

        draw_endpoints(ax, G, bundle.od_source, bundle.od_target)
        zoom_to(ax, G, all_paths)
        _set_geo_aspect(ax, G)
        _strip_axes(ax)
        ax.set_title(title, fontsize=10)

    # The after-panel stretches differ from the before-panel ones, so they
    # go in the panel title rather than being silently folded into one
    # legend entry.
    after_bits = []
    for record in sorted(records, key=lambda r: style.ALGO_ORDER.index(_series_key(r))):
        if record.stretch_after is None:
            continue
        after_bits.append(f"{style.label(_series_key(record))} {record.stretch_after:.3f}")
    axes[1].set_title(
        f"after {bundle.scenario_id} closure "
        f"({n_corridors} corridors closed, {len(bundle.removed_edges)} directed edges)\n"
        "post-disruption stretch: " + "; ".join(after_bits),
        fontsize=9,
    )

    from matplotlib.lines import Line2D  # noqa: PLC0415

    handles.append(
        Line2D([], [], color=style.REMOVED_EDGE, linewidth=2.6)
    )
    labels.append("closed road")
    handles.append(
        Line2D([], [], color=style.BASEMAP_EDGE, linewidth=1.2)
    )
    labels.append("street network")
    handles.append(
        Line2D(
            [], [], color=style.NODE_SOURCE, marker="o", markersize=6,
            markeredgecolor="white", linestyle="none",
        )
    )
    labels.append(f"origin ({bundle.od_source})")
    handles.append(
        Line2D(
            [], [], color=style.NODE_TARGET, marker="*", markersize=11,
            markeredgecolor="white", linestyle="none",
        )
    )
    labels.append(f"destination ({bundle.od_target})")

    fig.legend(handles, labels, loc="lower center", ncol=3, bbox_to_anchor=(0.5, -0.22))
    fig.suptitle(
        f"Re-routing after {bundle.scenario_id} — {bundle.stratum} pair "
        f"{bundle.od_source}→{bundle.od_target} "
        f"({bundle.distance_m:.0f} m apart), SUMO "
        f"{bundle.traffic_level}, "
        f"{'warm' if bundle.warm_start else 'cold'} start\n"
        "illustrative re-run — not the sweep's measured results",
        fontsize=10,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.90))

    out_stem = Path(out_stem)
    out_stem.parent.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for ext in ("png", "svg"):
        path = out_stem.with_suffix(f".{ext}")
        fig.savefig(path)
        written.append(path)
    plt.close(fig)
    return written



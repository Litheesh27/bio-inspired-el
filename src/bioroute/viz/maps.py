FIG6_CAPTION = (
    "Figure 6. Per-edge congestion under SUMO light and heavy demand on the "
    "`sumo_speeds` baseline: colour is congested travel time divided by that "
    "edge's free-flow travel time, i.e. 1.0 = free-flow. ONE SHARED COLOUR "
    "SCALE across both panels (a per-panel scale would make the comparison "
    "meaningless), clipped at the {vmax:.1f}x bound named in the colourbar "
    "label; the colourbar's arrow marks that clip. A large unaffected "
    "fraction is expected: CLAUDE.md Phase 2d reports that 61% of SUMO edges "
    "see no vehicle even at heavy demand, and this snapshot confirms it "
    "(frac_sumo_edges_zero_traffic 0.68 light / 0.61 heavy). "
    "**That 61% is NOT the pale fraction of this map, and the difference is "
    "worth stating rather than glossing.** Only {share_light:.0%} (light) "
    "and {share_heavy:.0%} (heavy) of GRAPH edges sit at exactly 1.0, and "
    "they are precisely the edges with no traveltime observation at all "
    "(n_fallback_edges 1,616 / 812 of 7,015 — the counts match exactly). "
    "netconvert splits ways while OSMnx merges them, so one graph edge "
    "aggregates several SUMO segments and reports a non-unit ratio if ANY of "
    "them carried traffic. Absolute times on this baseline are optimistic "
    "for Bengaluru (Phase 2d: mean speed 51.5 km/h); ratios are comparable, "
    "absolute values are not. ILLUSTRATIVE: a snapshot property, regenerated "
    "by Phase 9b — the results Parquet has no per-edge column."
)


def congestion_colormap(name: str = "magma_r", lo: float = 0.08, hi: float = 0.98):
    """A truncated `magma_r`: perceptually uniform, light -> dark.

    Truncated rather than used whole because `magma_r` starts at
    near-white, and a ratio-1.0 edge would then be invisible against a
    white panel -- the figure would silently drop the majority of the
    network. Starting at 0.08 keeps the free-flow end pale (correctly
    recessive) but visible. Sequential data gets a single-direction
    light-to-dark ramp; a rainbow map here would invent category
    boundaries that the ratio does not have.
    """
    import numpy as np  # noqa: PLC0415
    from matplotlib.colors import LinearSegmentedColormap  # noqa: PLC0415
    from matplotlib import colormaps  # noqa: PLC0415

    base = colormaps[name]
    return LinearSegmentedColormap.from_list(
        f"{name}_trunc", base(np.linspace(lo, hi, 256))
    )


def _ratio_key(key: str) -> tuple[int, int, int]:
    u, v, k = key.split("|")
    return int(u), int(v), int(k)


def plot_congestion_heatmap(
    G: nx.MultiDiGraph,
    ratios_by_level: Mapping[str, Mapping[str, float]],
    out_stem: str | Path,
    summary: Mapping[str, Any] | None = None,
    levels: Sequence[str] = ("light", "heavy"),
    vmax: float | None = None,
    vmax_quantile: float = 0.95,
) -> tuple[list[Path], dict[str, Any]]:
    """Render figure 6 to PNG + SVG. Returns `(paths, scale_info)`.

    `vmax` defaults to the `vmax_quantile` quantile of the POOLED ratios
    across both levels, so the scale is shared by construction and a
    handful of extreme edges cannot flatten the whole map.

    0.95 rather than something like 0.995 because the distribution is very
    long-tailed on top of a tight body: median 1.30/1.36 and p90 2.08/2.35,
    but p99 6.0/16.6 and a maximum of 59x. Scaling to the extremes would
    push ~95% of the network into the bottom sixth of the ramp and the map
    would read as "no congestion anywhere", which is false. The clip is
    returned, named in the colourbar label, and flagged by the colourbar's
    `extend="max"` arrow -- an undeclared clip would be a misreport.
    """
    import matplotlib.pyplot as plt  # noqa: PLC0415
    from matplotlib.collections import LineCollection  # noqa: PLC0415

    style.apply_style()

    pooled = sorted(
        float(v) for level in levels for v in ratios_by_level[level].values()
    )
    if vmax is None:
        if not pooled:
            raise ValueError("no congestion ratios to plot")
        vmax = float(pooled[min(len(pooled) - 1, int(vmax_quantile * (len(pooled) - 1)))])
    vmax = max(float(vmax), 1.05)
    cmap = congestion_colormap()

    fig, axes = plt.subplots(1, len(levels), figsize=(5.4 * len(levels), 5.6))
    if len(levels) == 1:
        axes = [axes]

    mappable = None
    for ax, level in zip(axes, levels):
        ratios = ratios_by_level[level]
        # Uncongested edges underneath, congested on top: otherwise a dense
        # grid of free-flow edges drawn last erases the arterials, which is
        # the one thing the figure exists to show.
        items = sorted(ratios.items(), key=lambda kv: float(kv[1]))
        segments = []
        values = []
        for key, ratio in items:
            u, v, k = _ratio_key(key)
            if not G.has_edge(u, v, k):
                continue
            segments.append(edge_points(G, u, v, k))
            values.append(min(float(ratio), vmax))
        lc = LineCollection(
            segments, cmap=cmap, linewidths=0.75, zorder=2
        )
        lc.set_array(values)
        lc.set_clim(1.0, vmax)
        ax.add_collection(lc)
        ax.autoscale_view()
        mappable = lc

        above = sum(1 for r in ratios.values() if float(r) > vmax)
        bits = [f"{len(segments)} edges"]
        if summary and level in summary:
            s = summary[level]
            bits.append(f"median {s['median']:.2f}x")
            bits.append(f"p90 {s['p90']:.2f}x")
            bits.append(f"{s['share_at_freeflow']:.0%} at free-flow")
        # Say how much of the network the clip actually affects, in the
        # panel rather than only in the caption.
        bits.append(f"{above / max(len(ratios), 1):.1%} above clip")
        # Two short lines rather than one long one: at this figure width a
        # single-line subtitle runs into the neighbouring panel's.
        ax.set_title(
            f"SUMO {level} demand\n"
            + " · ".join(bits[:3])
            + "\n"
            + " · ".join(bits[3:]),
            fontsize=8,
        )
        _set_geo_aspect(ax, G)
        _strip_axes(ax)

    cbar = fig.colorbar(
        mappable,
        ax=axes,
        fraction=0.030,
        pad=0.015,
        shrink=0.78,
        extend="max",
        # Default `extendfrac` sizes the arrow as a fraction of the bar and
        # renders as a huge black wedge here; keep it a marker, not a mark.
        extendfrac=0.02,
    )
    cbar.set_label(
        f"congested / free-flow travel time  (x, clipped at {vmax:.1f}x)",
        fontsize=9,
    )

    fig.suptitle(
        "Per-edge congestion, SUMO light vs heavy (shared colour scale)\n"
        "illustrative snapshot property — not the sweep's measured results",
        fontsize=10,
    )

    out_stem = Path(out_stem)
    out_stem.parent.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for ext in ("png", "svg"):
        path = out_stem.with_suffix(f".{ext}")
        fig.savefig(path)
        written.append(path)
    plt.close(fig)

    return written, {"vmax": vmax, "vmax_quantile": vmax_quantile, "vmin": 1.0}

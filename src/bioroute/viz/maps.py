def draw_basemap(
    ax,
    G: nx.MultiDiGraph,
    color: str = style.BASEMAP_EDGE,
    linewidth: float = 0.35,
    zorder: int = 1,
) -> None:
    """The whole street network, deliberately recessive.

    Drawn as ONE `LineCollection` rather than 7,015 `plot` calls: the
    per-artist overhead otherwise dominates, and the SVG would carry one
    element per edge.
    """
    from matplotlib.collections import LineCollection  # noqa: PLC0415

    segments = [edge_points(G, u, v, k) for u, v, k in G.edges(keys=True)]
    ax.add_collection(
        LineCollection(
            segments, colors=color, linewidths=linewidth, zorder=zorder
        )
    )
    ax.autoscale_view()


def draw_removed(
    ax,
    G: nx.MultiDiGraph,
    removed_edges: Iterable[Sequence[int]],
    color: str = style.REMOVED_EDGE,
    linewidth: float = 2.6,
    zorder: int = 6,
) -> int:
    """Closed roads: black, thick, on top of everything but the markers.

    Returns the number of distinct (u, v) corridors drawn. Phase 7 closes
    the reverse direction and every parallel edge, so the edge COUNT
    overstates how much road is shut; the corridor count is the honest
    number for a caption.
    """
    from matplotlib.collections import LineCollection  # noqa: PLC0415

    seen: set[tuple[int, int]] = set()
    segments = []
    for edge in removed_edges:
        u, v = int(edge[0]), int(edge[1])
        pair = (min(u, v), max(u, v))
        if pair in seen:
            continue
        seen.add(pair)
        if not G.has_node(u) or not G.has_node(v):
            continue
        segments.append(edge_points(G, u, v))
    if segments:
        ax.add_collection(
            LineCollection(
                segments,
                colors=color,
                linewidths=linewidth,
                zorder=zorder,
                capstyle="round",
            )
        )
    return len(segments)


def draw_route(
    ax,
    G: nx.MultiDiGraph,
    path: Sequence[int],
    color: str,
    linewidth: float = 2.0,
    alpha: float = 0.95,
    zorder: int = 4,
    halo: bool = True,
    linestyle: Any = "-",
    transform=None,
):
    """One route. Returns the drawn `Line2D`, for a legend handle.

    `halo` paints a white 2px-wider line underneath, the surface ring that
    keeps three overlapping routes separable where they share a corridor --
    without it the topmost colour simply hides the others. A route drawn
    dashed on purpose (A* over Dijkstra) must pass `halo=False`, or the
    halo fills the gaps and erases the line below.
    """
    pts = path_points(G, path)
    if not pts:
        return None
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    extra = {} if transform is None else {"transform": transform}
    if halo:
        ax.plot(
            xs,
            ys,
            color="white",
            linewidth=linewidth + 1.6,
            solid_capstyle="round",
            zorder=zorder - 1,
            **extra,
        )
    (line,) = ax.plot(
        xs,
        ys,
        color=color,
        linewidth=linewidth,
        alpha=alpha,
        linestyle=linestyle,
        solid_capstyle="round",
        zorder=zorder,
        **extra,
    )
    return line


def draw_endpoints(ax, G: nx.MultiDiGraph, source: int, target: int) -> None:
    """Source as a filled circle, target as a star, both ringed in white."""
    for node, marker, size in ((source, "o", 7.0), (target, "*", 13.0)):
        ax.plot(
            float(G.nodes[node]["x"]),
            float(G.nodes[node]["y"]),
            marker=marker,
            markersize=size,
            color=style.NODE_SOURCE,
            markeredgecolor="white",
            markeredgewidth=1.0,
            linestyle="none",
            zorder=8,
        )


def zoom_to(
    ax,
    G: nx.MultiDiGraph,
    paths: Sequence[Sequence[int]],
    pad_frac: float = 0.12,
) -> None:
    """Frame the panel on the union of `paths`, with padding.

    The study area is 4x4 km and a route may occupy a corner of it, so a
    full-extent panel would render the interesting part a few millimetres
    wide. Both panels of figure 5 are framed on the SAME union so the
    before/after comparison is not a pan as well as a re-route.
    """
    xs: list[float] = []
    ys: list[float] = []
    for path in paths:
        for x, y in path_points(G, path):
            xs.append(x)
            ys.append(y)
    if not xs:
        return
    dx = max(max(xs) - min(xs), 1e-4)
    dy = max(max(ys) - min(ys), 1e-4)
    pad = pad_frac * max(dx, dy)
    ax.set_xlim(min(xs) - pad, max(xs) + pad)
    ax.set_ylim(min(ys) - pad, max(ys) + pad)



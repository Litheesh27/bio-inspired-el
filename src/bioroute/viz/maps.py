"""Network map figures drawn on the real Bengaluru street geometry.

IMPLEMENTED IN: Phase 9 (the map half of Phase 9b).

Contains figure 5 (the three algorithms' routes before and after a
disruption) and figure 6 (the congestion heatmap, light vs heavy). Both are
geographic, which is why they live here rather than in `viz/figures.py`;
their input artifacts are regenerated by `viz/traces.py` and written by
`scripts/06_make_traces.py`.

**BOTH FIGURES ARE ILLUSTRATIVE AND COME FROM A SEEDED RE-RUN, NOT FROM
THE SWEEP'S RESULTS PARQUET.** The Parquet records `path_hops` but not the
paths themselves, and a congestion ratio is a property of the
`TrafficSnapshot` rather than of any result row, so neither figure has a
source column in the measured data. Every caption here says so.

--------------------------------------------------------------------------
TWO NON-COSMETIC RULES
--------------------------------------------------------------------------

1. **Physarum's route is labelled with its extraction provenance.**
   CLAUDE.md Phase 9 forbids presenting a fallback-derived path as the
   model's own output, and ~70% of Physarum's reported paths came from a
   fallback (Phase 8e). On a map that error is at its most convincing: a
   green line that is really Dijkstra's line looks like the model solved
   the problem. So `max_flux_walk` is drawn in the model-only colour and
   anything else is drawn in the with-fallback colour, with the method
   named in the legend either way.

2. **Equal aspect ratio, corrected for latitude.** Geometry comes from the
   graph's own node `x`/`y` (lon/lat in degrees) and OSMnx edge
   `geometry` where present. One degree of longitude is `cos(lat)` of one
   degree of latitude, so plotting degrees on an equal-aspect axis would
   stretch Bengaluru east-west by ~3%. `_set_geo_aspect` applies the
   cos(lat) correction instead of calling `set_aspect("equal")` on raw
   degrees.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

import networkx as nx

from bioroute.viz import style

# ==========================================================================
# Geometry helpers
# ==========================================================================


def edge_points(
    G: nx.MultiDiGraph, u: int, v: int, k: int | None = None
) -> list[tuple[float, float]]:
    """(lon, lat) vertices for one edge.

    Uses the OSMnx `geometry` LineString when the edge carries one (merged
    ways are curved, and a straight segment between the endpoints would cut
    across blocks), and falls back to the two endpoints otherwise. On a
    parallel-edge pair with `k=None` the first available key is used.
    """
    data: Mapping[str, Any] | None = None
    if k is None:
        bundle = G.get_edge_data(u, v)
        if bundle:
            data = bundle[sorted(bundle)[0]]
    else:
        data = G.get_edge_data(u, v, k)

    if data is not None:
        geom = data.get("geometry")
        coords = getattr(geom, "coords", None)
        if coords is not None:
            return [(float(x), float(y)) for x, y in coords]

    return [
        (float(G.nodes[u]["x"]), float(G.nodes[u]["y"])),
        (float(G.nodes[v]["x"]), float(G.nodes[v]["y"])),
    ]


def path_points(
    G: nx.MultiDiGraph, path: Sequence[int]
) -> list[tuple[float, float]]:
    """Concatenated geometry along a node path, de-duplicating joins."""
    out: list[tuple[float, float]] = []
    for u, v in zip(path, path[1:]):
        seg = edge_points(G, u, v)
        # OSMnx geometry is stored in the edge's own direction, which for a
        # reversed edge runs v->u. Orient each segment so the drawn line
        # actually follows the route.
        if seg and out and _dist2(seg[-1], out[-1]) < _dist2(seg[0], out[-1]):
            seg = list(reversed(seg))
        if out and seg and seg[0] == out[-1]:
            seg = seg[1:]
        out.extend(seg)
    return out


def _dist2(a: tuple[float, float], b: tuple[float, float]) -> float:
    return (a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2


def _set_geo_aspect(ax, G: nx.MultiDiGraph) -> None:
    """Equal-distance aspect for lon/lat degrees (see the module docstring)."""
    lats = [float(d["y"]) for _, d in G.nodes(data=True)]
    mid = math.radians(sum(lats) / len(lats)) if lats else 0.0
    ax.set_aspect(1.0 / max(math.cos(mid), 1e-6))


def _strip_axes(ax) -> None:
    """A map has no meaningful x/y ticks: lon/lat numbers add nothing a
    reader can use and crowd a panel that is already dense with lines."""
    ax.set_xticks([])
    ax.set_yticks([])
    ax.grid(False)
    for spine in ax.spines.values():
        spine.set_visible(False)



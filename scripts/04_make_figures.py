"""Phase 9a: regenerate every results-table figure, the stats bundle and
the summary tables from the sweep Parquet, with one command.

    .venv/Scripts/python.exe scripts/04_make_figures.py
    .venv/Scripts/python.exe scripts/04_make_figures.py --only fig04
    .venv/Scripts/python.exe scripts/04_make_figures.py --format png

What it writes:

  figures/fig02_recovery_by_scenario.{png,svg}
  figures/fig03_stretch_pre_post.{png,svg}
  figures/fig04_pareto_recovery_vs_quality.{png,svg}   <- the money figure
  figures/fig07_warm_vs_cold.{png,svg}
  docs/results/summary.md                 every table, with n and CIs
  data/results/stats_<confighash>.json    compute_all(), for the dashboard

Figures 1, 5 and 6 need per-iteration traces and network geometry rather
than the results table; they are produced by `scripts/06_make_traces.py`.

The input file is READ-ONLY here. `data/results/final_14a535c02b83.parquet`
is the committed experimental evidence (Phase 8e); re-running the sweep to
recover it costs ~10 h of wall-clock, so nothing in Phase 9 writes to it.

Every number printed or written by this script carries its n, and every
median carries a bootstrap CI. That is not decoration: Phase 4d found a
single-seed in-sample estimate that landed exactly on the upper CI bound
of the clean measurement, which is why this project does not report a
point estimate without its interval.
"""


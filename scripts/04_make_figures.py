# --- markdown rendering ----------------------------------------------------


def _fmt(value: Any, digits: int = 4) -> str:
    """Format one cell, with nulls shown as an em dash rather than 0."""
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "--"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return f"{value:,}"
    if isinstance(value, float):
        if value != 0 and (abs(value) < 1e-3 or abs(value) >= 1e6):
            return f"{value:.2e}"
        return f"{value:.{digits}f}"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value)
    return str(value)


def _ci(low: Any, high: Any, digits: int = 4) -> str:
    if low is None or high is None or pd.isna(low) or pd.isna(high):
        return "--"
    return f"[{_fmt(low, digits)}, {_fmt(high, digits)}]"


def _iqr(q1: Any, q3: Any, digits: int = 4) -> str:
    if q1 is None or q3 is None or pd.isna(q1) or pd.isna(q3):
        return "--"
    return f"{_fmt(q1, digits)}-{_fmt(q3, digits)}"


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def _pct(value: Any) -> str:
    """A share as a percentage, with a second decimal for small ones.

    0.51% of runs failed; rounding that to "0.5%" would quietly restate a
    number the project reports to two decimals.
    """
    if value is None or pd.isna(value):
        return "--"
    pct = 100 * float(value)
    return f"{pct:.2f}%" if 0 < pct < 1 else f"{pct:.1f}%"


def write_summary(df: pd.DataFrame, bundle: dict[str, Any], path: Path) -> Path:
    """Render every table as markdown, each with its n and its exclusions.

    This file is what the deferred paper gets written from, so each table
    is followed by a "how to read this" note. Those notes are the place
    where a methodological trap is spelled out once, instead of being
    rediscovered by whoever quotes the number.
    """
    quality = pd.DataFrame(bundle["quality"])
    recovery = pd.DataFrame(bundle["recovery"])
    warm_cold = pd.DataFrame(bundle["warm_vs_cold"])
    provenance = pd.DataFrame(bundle["provenance"])
    scenario = pd.DataFrame(bundle["scenario"])
    congestion = pd.DataFrame(bundle["congestion_effect"])
    failures = pd.DataFrame(bundle["failures"])
    meta = bundle["meta"]
    head = bundle["headline"]

    parts: list[str] = []
    parts.append(f"""# Phase 9a results summary

Generated by `scripts/04_make_figures.py` from
`{stats.DEFAULT_PARQUET.name}` -- {_fmt(meta['n_rows'])} rows x
{meta['n_columns']} columns, the committed Phase 8 sweep. Nothing here is
computed from any other source.

**Design.** {_fmt(meta['n_od_pairs'])} OD pairs x
{len(meta['scenarios'])} scenarios x {len(meta['traffic_levels'])} traffic
levels x {{warm, cold}} = {_fmt(meta['n_cells_designed'])} cells,
{_fmt(meta['n_rows'])} runs. Congestion:
{', '.join(meta['congestion_source'])} on the
`{', '.join(meta['baseline_graph'])}` baseline graph (hash
`{', '.join(meta['baseline_hash'])}`). Seeds per algorithm:
{', '.join(f"{a} {len(s)}" for a, s in meta['seeds_per_algorithm'].items())}.

**Statistics.** Median + IQR throughout (never means: these distributions
are right-skewed and, for Physarum's warm recovery, bimodal). Paired
Wilcoxon signed-rank on identical
`{', '.join(meta['statistics']['pairing_keys'])}` tuples, exact zero
differences dropped. 95% CIs from a two-stage clustered bootstrap
({_fmt(meta['statistics']['n_boot'])} resamples, seed
{meta['statistics']['bootstrap_seed']}): OD pairs resampled first, then
seeds within each drawn pair, because rows from one OD pair are not
independent.

**Exclusions.** {_fmt(meta['n_failed'])} rows ({_pct(meta['failed_share'])})
carry `failed=True` and are excluded from every quality statistic below.
Each table states how many of its own rows that cost it. They are listed in
full at the end -- a recorded failure is never silently dropped.

**The one rule that shapes every Physarum row below.** Physarum appears as
TWO series, never pooled: *with fallback* (`physarum`, the `stretch`
columns as recorded) and *model only* (`physarum_walk`,
`walk_best_stretch` / `post_disruption_walk_stretch`, i.e. the max-flux
walk's own result). About {_pct(head['physarum_walk_any_path_share_all_rows'])}
of Physarum rows have a walk path at all, and the median stretch is exactly
1.000 inside every provenance class -- so a pooled Physarum number can
mean "Dijkstra's own path, via the fallback".
""")

    # --- headline ----------------------------------------------------------
    wvc = head["warm_vs_cold"]
    bim = head["physarum_bimodality"]
    aco_cong = head["aco_congestion_effect_sumo"]
    pvm = head["physarum_pooled_vs_model_only"]
    parts.append(f"""
## Headline numbers

| Claim | Number | Evidence |
|---|---|---|
| Warm start cuts Physarum's recovery iterations | **{_fmt(wvc['physarum']['recovery_iterations']['median_paired_ratio'], 2)}x** (paired median ratio) | n={_fmt(wvc['physarum']['recovery_iterations']['n_pairs'])} pairs, warm faster on {_fmt(wvc['physarum']['recovery_iterations']['n_a_better'])}, Wilcoxon p={_fmt(wvc['physarum']['recovery_iterations']['pvalue'], 2)} |
| ... and its wall-clock | **{_fmt(wvc['physarum']['recovery_wallclock_s']['median_paired_ratio'], 2)}x** (paired median ratio) | n={_fmt(wvc['physarum']['recovery_wallclock_s']['n_pairs'])}, warm faster on {_fmt(wvc['physarum']['recovery_wallclock_s']['n_a_better'])}, p={_fmt(wvc['physarum']['recovery_wallclock_s']['pvalue'], 2)} |
| Warm start recovers in a SINGLE iteration | **{_pct(bim['warm_share_exactly_1_iteration'])}** of warm recoveries | n={_fmt(bim['n_warm'])}; cold does so {_pct(bim['cold_share_exactly_1_iteration'])} of the time and its minimum is {_fmt(bim['cold_min_iterations'], 0)} iterations |
| Warm start also helps ACO | **{_fmt(wvc['aco']['recovery_iterations']['median_paired_ratio'], 2)}x** iterations / {_fmt(wvc['aco']['recovery_wallclock_s']['median_paired_ratio'], 2)}x wall-clock | n={_fmt(wvc['aco']['recovery_iterations']['n_pairs'])} pairs, p={_fmt(wvc['aco']['recovery_iterations']['pvalue'], 2)} |
| SUMO congestion HURTS ACO's quality | within-10% {_pct(aco_cong['within_10pct_light'])} light vs {_pct(aco_cong['within_10pct_heavy'])} heavy | paired on (OD, seed), n={_fmt(aco_cong['n_pairs'])}, p={_fmt(aco_cong['pvalue'], 3)}; {_fmt(aco_cong['n_pass_light_only'])} pairs pass under light only vs {_fmt(aco_cong['n_pass_heavy_only'])} under heavy only |
| Physarum's pooled competence is mostly the fallback's | exact-match {_pct(pvm['light']['pooled_exact_match_share'])} / {_pct(pvm['heavy']['pooled_exact_match_share'])} pooled (light/heavy) vs **{_pct(pvm['light']['walk_only_exact_match_share'])} / {_pct(pvm['heavy']['walk_only_exact_match_share'])} model-only** | n={_fmt(pvm['light']['n'])} per level, undisrupted solve |
| Dijkstra and A* remain the honest baseline | stretch 1.000, recovery in 1 iteration | {_fmt(head['classical_sanity']['dijkstra']['median_recovery_wallclock_s'], 3)} s (Dijkstra) / {_fmt(head['classical_sanity']['astar']['median_recovery_wallclock_s'], 3)} s (A*) median recovery |

**Congestion-direction caveat.** {head['congestion_model_caveat']}

**How to read the warm-start numbers.** The ratio is the median of
per-pair ratios, never a ratio of the two medians. Physarum's warm
`recovery_iterations` distribution has modes at 1 and ~50, so the ratio of
its median ({_fmt(bim['warm_median_iterations'], 0)}) to cold's
({_fmt(bim['cold_median_iterations'], 0)}) is not a valid statistic -- the
version of that calculation on wall-clock produced a "24x" that Phase 8e
retired. "Warm start recovers in a single iteration on nearly half of all
closures, which cold start never does" is both truer and stronger.
""")

    # --- quality -----------------------------------------------------------
    rows = []
    for r in quality.to_dict(orient="records"):
        rows.append([
            r["label"], r["traffic_level"], _fmt(r["n"]),
            _fmt(r["n_with_value"]), _fmt(r["median"]),
            _iqr(r["q1"], r["q3"]), _ci(r.get("ci_low"), r.get("ci_high")),
            _pct(r["exact_match_share"]), _pct(r["within_10pct_share"]),
            _fmt(r["n_failed_excluded"]),
        ])
    parts.append(f"""
## Table 1 -- Pre-disruption path quality

{_table(
    ["series", "traffic", "n", "n with value", "median stretch", "IQR",
     "95% CI (median)", "exact match", "within 10%", "failed excluded"],
    rows,
)}

**How to read this.** One row per initial solve: the pre-disruption solve
is identical across all seven scenarios and both start modes for a given
(algorithm, OD pair, traffic level, seed), verified on every group, so the
rows are deduplicated on exactly that key. Pooling all 5,492 successful
rows instead would count one solve up to 13 times and shrink every CI by a
factor that is pure bookkeeping. `traffic = all` pools the two SUMO levels;
that is legitimate for stretch because each value is already normalised by
Dijkstra on its own level, and it would NOT be legitimate for raw costs.

`n` counts every successful row of the series; `n with value` counts the
subset where the measurement exists. They differ only for *Physarum (model
only)*, where a null means the max-flux walk never completed a path at
all. That is not an exact match, so the exact-match and within-10% shares
use `n` as the denominator while the median, IQR and CI necessarily use
`n with value`. Reading the model-only median without that in mind reads a
conditional statistic as an unconditional one.

The failed-excluded column counts `failed=True` rows for that series; all
are S4, and because the initial solve repeats across scenarios the dedup
still recovers every initial solve from a surviving scenario, so no
measurement is lost here -- only rows.
""")

    # --- recovery ----------------------------------------------------------
    rows = []
    for r in recovery.to_dict(orient="records"):
        rows.append([
            r["label"], r["start"], _fmt(r["n"]),
            _fmt(r["iters_median"], 1), _iqr(r["iters_q1"], r["iters_q3"], 1),
            _ci(r.get("iters_ci_low"), r.get("iters_ci_high"), 1),
            _fmt(r["wall_median_s"], 3),
            _iqr(r["wall_q1_s"], r["wall_q3_s"], 3),
            _ci(r.get("wall_ci_low_s"), r.get("wall_ci_high_s"), 3),
            _pct(r["share_1_iteration"]),
            _fmt(r["median_s_per_iteration"], 4),
            _fmt(r["n_failed_excluded"]),
        ])
    parts.append(f"""
## Table 2 -- Recovery cost, warm vs cold

{_table(
    ["algorithm", "start", "n", "median iters", "IQR", "95% CI",
     "median wall-clock (s)", "IQR (s)", "95% CI (s)", "share 1 iteration",
     "median s/iteration", "failed excluded"],
    rows,
)}

**How to read this.** S1-S6 only: S0 is the no-disruption control and its
recovery columns are null by schema, so it contributes nothing rather than
a zero. The classical routers have cold rows only -- a one-shot router has
no warm mode, and duplicating their rows under a "warm" label would
fabricate a comparison.

`share 1 iteration` is the headline shape of the warm-start result, not a
footnote: Physarum's warm recoveries converge in exactly one iteration
nearly half the time while cold's minimum is 73, so the warm distribution
is bimodal and its median describes neither mode. Read it together with
Table 3's paired ratios and figure 7's ECDF, and do not divide the two
medians in this table.

`median s/iteration` is nearly identical warm vs cold for both bio-inspired
methods, which is the proof that warm start buys FEWER iterations rather
than cheaper ones -- the exact claim the project set out to test.
""")

    # --- paired warm/cold --------------------------------------------------
    rows = []
    for r in warm_cold.to_dict(orient="records"):
        rows.append([
            r["label"], f"`{r['metric']}`", _fmt(r["n_pairs"]),
            _fmt(r["median_warm"], 4), _fmt(r["median_cold"], 4),
            _fmt(r["median_paired_ratio_cold_over_warm"], 3),
            _fmt(r["n_warm_better"]), _fmt(r["n_cold_better"]),
            _fmt(r["n_tied"]), _fmt(r["pvalue"], 3),
            f"{_fmt(r['n_warm_only'])} / {_fmt(r['n_cold_only'])}",
        ])
    parts.append(f"""
## Table 3 -- Paired warm-vs-cold comparison

{_table(
    ["algorithm", "metric", "n pairs", "median warm", "median cold",
     "paired median ratio cold/warm", "warm better", "cold better", "tied",
     "Wilcoxon p", "warm-only / cold-only cells"],
    rows,
)}

**How to read this.** Paired on identical (OD pair, scenario, traffic
level, seed); the medians shown are over the PAIRED cells only, so they
will not always equal the unpaired medians in Table 2. A ratio above 1
means warm start won. Lower is better for every metric here.

The last column is a coverage warning and it matters on
`post_disruption_walk_stretch`: the warm side produces a walk path on far
fewer cells than the cold side, so the two unpaired samples are composed
differently and comparing their medians reverses the sign of the effect.
On the cells where both sides produce a path, cold's walk is marginally
better -- see `docs/results/phase9a_notes.md`. Warm start's robust win is
SPEED, not extraction quality.

Ties are large on the quality metrics because both start modes frequently
find the same optimal path; they are dropped from the signed-rank test (as
the statistic requires) but reported here, since a tie is signal rather
than noise.
""")

    # --- provenance --------------------------------------------------------
    rows = []
    for r in provenance.to_dict(orient="records"):
        rows.append([
            f"`{r['best_path_extraction_method']}`",
            "yes" if r["is_model_own_extraction"] else "no",
            _fmt(r["n"]), _pct(r["share_of_physarum_rows"]),
            _fmt(r["median_stretch"]), _iqr(r["q1"], r["q3"]),
            _pct(r["exact_match_share"]),
            _fmt(r["median_post_disruption_stretch"]),
        ])
    parts.append(f"""
## Table 4 -- Physarum path provenance

{_table(
    ["best_path_extraction_method", "model's own extraction", "n",
     "share of Physarum rows", "median stretch", "IQR", "exact match",
     "median post-disruption stretch"],
    rows,
)}

**How to read this.** This table is the evidence for the no-pooling rule.
The median stretch is **exactly 1.000 in every class**, so a pooled median
cannot distinguish "the model found the optimum" from "the fallback handed
back Dijkstra's own path" -- and `full_graph_fallback` IS plain Dijkstra.
The exact-match shares, by contrast, separate the classes clearly, which
is why the figures report shares and provenance alongside medians.

The column is `best_path_extraction_method`, which records the method that
produced the path actually REPORTED (tracked at the iteration where
`best_cost` improved), not `extraction_method`, which only says how the
final iteration happened to end. The two disagree on a large minority of
rows (Phase 8b).
""")

    # --- scenario ----------------------------------------------------------
    rows = []
    for r in scenario.to_dict(orient="records"):
        # The model-only row repeats the with-fallback row's recovery
        # columns BY CONSTRUCTION (same solve, different extraction). The
        # marker goes in the row itself because a reviewer scans the table
        # before the prose below it, and six pairs of duplicated numbers
        # otherwise read as a copy-paste error.
        label = r["label"] + (
            " †" if r["series"] == "physarum_walk" else ""
        )
        rows.append([
            r["scenario_id"], label, _fmt(r["n"]),
            _fmt(r["n_with_post_value"]),
            _fmt(r["post_stretch_median"]),
            _iqr(r["post_stretch_q1"], r["post_stretch_q3"]),
            _fmt(r["post_stretch_max"]),
            _pct(r["post_exact_match_share"]),
            _fmt(r["recovery_iters_median"], 1),
            _iqr(r["recovery_iters_q1"], r["recovery_iters_q3"], 1),
            _fmt(r["recovery_wall_median_s"], 3),
            _fmt(r["n_removed_edges_median"], 0),
            _fmt(r["n_failed_excluded"]),
        ])
    parts.append(f"""
## Table 5 -- Per-scenario post-disruption quality and recovery cost

{_table(
    ["scenario", "series", "n", "n with post value",
     "median post stretch", "IQR", "max", "exact match",
     "median recovery iters", "IQR", "median recovery s",
     "median edges closed", "failed excluded"],
    rows,
)}

† shares the solve with the row above -- identical recovery columns are
by construction. The model-only series differs in how the path is
extracted, not in the solve, so it has the same iterations and the same
seconds. Only the quality columns differ -- which is precisely the
quantity the no-pooling rule protects.

**How to read this.** S0 is absent by construction: it is the
no-disruption control and has no post-disruption measurement. Scenarios
are in severity order, which Phase 7 MEASURED rather than assumed -- its
rejection rates (S1 2.6%, S3 14.5%, S4 31.7%) show fragility is
super-additive in the number of simultaneous closures, while a whole
corridor (S5) is safer than five scattered edges because one detour routes
around all of it.

The `failed excluded` column is where S4's infeasibility surfaces: all
{_fmt(meta['n_failed'])} failures are S4 cells where no choice of 5 path
edges could be closed without disconnecting source from target. That is
the fragility result, not a bug.

S6 deserves its own caution. It closes every edge incident to a path node,
which isolates that node by construction, and before the Phase 8a fix
Physarum silently reported Dijkstra's path there at a fabricated stretch of
exactly 1.000 on every row. The numbers here are post-fix.
""")

    # --- congestion --------------------------------------------------------
    rows = []
    for r in congestion.to_dict(orient="records"):
        rows.append([
            r["label"], _fmt(r["n_pairs"]),
            _fmt(r["median_light"]), _fmt(r["median_heavy"]),
            _fmt(r["median_paired_ratio_heavy_over_light"], 3),
            _pct(r["within_10pct_light"]), _pct(r["within_10pct_heavy"]),
            _fmt(r["n_light_better"]), _fmt(r["n_heavy_better"]),
            _fmt(r["n_tied"]), _fmt(r["pvalue"], 3),
            f"{_fmt(r['n_pass_light_only'])} / {_fmt(r['n_pass_heavy_only'])}",
        ])
    parts.append(f"""
## Table 6 -- Congestion effect on the undisrupted solve (SUMO only)

{_table(
    ["series", "n pairs", "median light", "median heavy",
     "paired ratio heavy/light", "within 10% light", "within 10% heavy",
     "light better", "heavy better", "tied", "Wilcoxon p",
     "pass light-only / heavy-only"],
    rows,
)}

**How to read this -- and the one sentence that must travel with it.**
These are **{', '.join(meta['congestion_source'])} / {', '.join(meta['baseline_graph'])}**
numbers. Phase 4/4d measured the OPPOSITE sign on BPR / `config_speeds`,
where congestion flattened the cost surface and HELPED ACO. The sign of
the congestion effect is therefore a property of the congestion model, not
of the algorithm, and no claim from this table may say "under congestion"
without naming its model. Phase 2d warned that BPR and SUMO "bracket rather
than agree and must not be merged into a single congestion level"; this
table is the direct evidence.

Consequently the older framing "the two bio-inspired methods fail in
opposite directions under congestion" is NOT supported here: under SUMO
both degrade.

Comparing stretch across traffic levels is legitimate even though
comparing costs would not be: each stretch is already normalised by
Dijkstra on its own weighted graph, so the dimensionless ratios are
comparable while the seconds are not.
""")

    # --- failures ----------------------------------------------------------
    rows = [
        [r["scenario_id"], r["algorithm"], _fmt(r["n"]), r["failure_reason"]]
        for r in failures.to_dict(orient="records")
    ]
    parts.append(f"""
## Table 7 -- Every recorded failure

{_table(["scenario", "algorithm", "n", "failure_reason"], rows)}

**How to read this.** {_fmt(meta['n_failed'])} of {_fmt(meta['n_rows'])}
runs ({_pct(meta['failed_share'])}), one cause, affecting 2 of
{_fmt(meta['n_cells_designed'])} cells. CLAUDE.md requires failures to be
recorded rather than dropped, so they are listed here in full and every
table above states how many of its own rows they cost it. The sweep's exit
criterion was a failure rate under 5%.
""")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(parts), encoding="utf-8")
    return path


# --- main ------------------------------------------------------------------


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Phase 9a: figures, stats bundle and summary tables.",
    )
    parser.add_argument(
        "--parquet", type=Path, default=None,
        help="results Parquet (default: the committed Phase 8 sweep file)",
    )
    parser.add_argument(
        "--outdir", type=Path, default=None,
        help="figure output directory (default: figures/, or figures/ieee "
             "with --ieee)",
    )
    parser.add_argument(
        "--format", dest="formats", nargs="+", default=None,
        help="output formats (default: png svg; pdf png svg with --ieee)",
    )
    parser.add_argument(
        "--ieee", action="store_true",
        help="render the IEEE two-column paper variant into figures/ieee: "
             "3.5 in / 7.16 in widths at final size, 8 pt type floor, PDF "
             "for LaTeX. Implies --no-tables, so the stats bundle and "
             "summary.md -- which are rendering-independent evidence -- are "
             "left untouched.",
    )
    parser.add_argument(
        "--only", nargs="+", default=None,
        help=f"figure ids to render (default: all of "
             f"{', '.join(sorted(figures.FIGURES))})",
    )
    parser.add_argument(
        "--n-boot", type=int, default=stats.N_BOOT,
        help="bootstrap resamples (default: 10000; lower only for a smoke "
             "run -- a published CI uses the full count)",
    )
    parser.add_argument(
        "--no-tables", action="store_true",
        help="render figures only, skipping summary.md and the JSON bundle",
    )
    args = parser.parse_args(argv)
    mode = "ieee" if args.ieee else "screen"
    if args.outdir is None:
        args.outdir = ROOT / "figures" / "ieee" if args.ieee \
            else ROOT / "figures"
    if args.ieee:
        # The IEEE pass is PURELY a rendering variant. Writing the tables
        # again would rewrite data/results/stats_<hash>.json and
        # docs/results/summary.md for no reason, and those two files are
        # cited; a re-render must not be able to move them.
        args.no_tables = True

    df = stats.load_results(args.parquet)
    print(
        f"loaded {len(df):,} rows x {df.shape[1]} columns from "
        f"{(args.parquet or stats.DEFAULT_PARQUET).name}"
    )
    counts = df["algorithm"].value_counts().to_dict()
    print("  per algorithm: " + ", ".join(f"{k} {v:,}" for k, v in counts.items()))
    print(
        f"  {int(df['failed'].sum())} failed rows "
        f"({100 * df['failed'].mean():.2f}%), excluded from quality stats"
    )

    written = figures.make_figures(
        df, args.outdir, formats=args.formats, only=args.only, mode=mode,
    )
    print(f"  mode: {mode}  ->  {args.outdir}")
    for key, paths in written.items():
        print(f"  {key}: " + ", ".join(p.name for p in paths))

    if args.no_tables:
        return 0

    bundle = stats.compute_all(df, n_boot=args.n_boot)
    config_hash = bundle["meta"]["config_hash"][0]
    json_path = DATA_RESULTS / f"stats_{config_hash}.json"
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(
        json.dumps(bundle, indent=1, sort_keys=False), encoding="utf-8",
    )
    print(f"  stats bundle: {json_path.relative_to(ROOT)} "
          f"({json_path.stat().st_size / 1024:.0f} KB)")

    summary = write_summary(df, bundle, DOCS_RESULTS / "summary.md")
    print(f"  summary: {summary.relative_to(ROOT)}")
    return 0


